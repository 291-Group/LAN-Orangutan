// Package report renders a self-contained HTML summary of the network that can
// be saved and shared as a single file (no external assets).
package report

import (
	"html/template"
	"io"
	"time"

	"github.com/291-Group/LAN-Orangutan/internal/types"
)

// Data is everything the report template needs. Devices are expected already
// sorted and with their vendor resolved by the caller.
type Data struct {
	GeneratedAt  time.Time
	Total        int
	Online       int
	Offline      int
	NetworkCount int
	Devices      []types.Device
}

var tmpl = template.Must(template.New("report").Parse(reportHTML))

// Render writes the HTML report to w.
func Render(w io.Writer, d Data) error {
	return tmpl.Execute(w, d)
}

const reportHTML = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>LAN Orangutan &mdash; Network Report</title>
<style>
  :root { --fg:#16202e; --muted:#56637a; --border:#e4ecf6; --bg:#ffffff; --green:#2c9e6b; --grey:#8592a6; }
  * { box-sizing: border-box; }
  body { font-family: -apple-system, BlinkMacSystemFont, 'Segoe UI', Roboto, sans-serif; color: var(--fg); background: var(--bg); margin: 0; padding: 2rem; line-height: 1.5; }
  .wrap { max-width: 980px; margin: 0 auto; }
  h1 { font-size: 1.5rem; margin: 0 0 0.25rem; }
  .sub { color: var(--muted); font-size: 0.9rem; margin: 0 0 1.5rem; }
  .stats { display: flex; flex-wrap: wrap; gap: 1.75rem; margin: 0 0 1.5rem; padding: 1rem 1.25rem; border: 1px solid var(--border); border-radius: 12px; }
  .stat b { font-size: 1.35rem; }
  .stat span { color: var(--muted); font-size: 0.85rem; margin-left: 0.35rem; }
  table { width: 100%; border-collapse: collapse; font-size: 0.85rem; }
  th, td { text-align: left; padding: 0.5rem 0.6rem; border-bottom: 1px solid var(--border); vertical-align: top; }
  th { color: var(--muted); font-weight: 600; text-transform: uppercase; font-size: 0.72rem; letter-spacing: 0.03em; }
  td.mono { font-family: 'SF Mono', 'Fira Code', monospace; }
  .dot { display: inline-block; width: 8px; height: 8px; border-radius: 50%; }
  .dot.on { background: var(--green); }
  .dot.off { background: transparent; border: 1.5px solid var(--grey); }
  .muted { color: var(--muted); }
  footer { margin-top: 2rem; color: var(--muted); font-size: 0.8rem; }
  @media print { body { padding: 0; } .stats { break-inside: avoid; } thead { display: table-header-group; } }
</style>
</head>
<body>
<div class="wrap">
  <h1>&#129446; LAN Orangutan &mdash; Network Report</h1>
  <p class="sub">Generated {{.GeneratedAt.Format "Mon, 02 Jan 2006 at 15:04"}}</p>
  <div class="stats">
    <div class="stat"><b>{{.Total}}</b><span>devices</span></div>
    <div class="stat"><b>{{.Online}}</b><span>online</span></div>
    <div class="stat"><b>{{.Offline}}</b><span>offline</span></div>
    <div class="stat"><b>{{.NetworkCount}}</b><span>network{{if ne .NetworkCount 1}}s{{end}}</span></div>
  </div>
  <table>
    <thead>
      <tr><th></th><th>IP Address</th><th>Hostname</th><th>Type</th><th>MAC</th><th>Vendor</th><th>Group</th><th>Last Seen</th></tr>
    </thead>
    <tbody>
    {{range .Devices}}
      <tr>
        <td><span class="dot {{if .IsOnline}}on{{else}}off{{end}}" title="{{if .IsOnline}}online{{else}}offline{{end}}"></span></td>
        <td class="mono">{{.IP}}</td>
        <td>{{if .Hostname}}{{.Hostname}}{{else}}<span class="muted">&mdash;</span>{{end}}</td>
        <td>{{if .Type}}{{.Type}}{{else}}<span class="muted">&mdash;</span>{{end}}</td>
        <td class="mono">{{if .MAC}}{{.MAC}}{{else}}<span class="muted">&mdash;</span>{{end}}</td>
        <td>{{if .Vendor}}{{.Vendor}}{{else}}<span class="muted">&mdash;</span>{{end}}</td>
        <td>{{if .Group}}{{.Group}}{{else}}<span class="muted">&mdash;</span>{{end}}</td>
        <td class="muted">{{.LastSeen.Format "2006-01-02 15:04"}}</td>
      </tr>
    {{end}}
    </tbody>
  </table>
  <footer>Generated by LAN Orangutan &middot; 291 Group</footer>
</div>
</body>
</html>
`
